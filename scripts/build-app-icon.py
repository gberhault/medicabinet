def app_icon_bytes(root_dir):
    """Bytes of icon files each app bundles (the Play assets are not part of either app)."""
    root = load_source(root_dir / SOURCE_RELATIVE)
    paths = list(text_outputs(root)) + list(BINARY_ASSETS)
    return {app: sum((root_dir / path).stat().st_size for path in paths
                     if path.parts[0] == app and (root_dir / path).is_file())
            for app in ("android", "ios")}


def check_size_budget(root_dir):
    for app, size in app_icon_bytes(root_dir).items():
        if size > APP_BUDGET_BYTES:
            raise IconError(f"the {app} icon files weigh {size} bytes, over the {APP_BUDGET_BYTES} bytes budget (X1)")


def check_placement(root_dir):
    """Play listing assets live under design/, never inside an app (P4)."""
    for app_source in ("android/app/src", "ios/MediCabinet"):
        for name in (PLAY_ICON.name, PLAY_GRAPHIC.name):
            for found in sorted((root_dir / app_source).rglob(name)):
                raise IconError(f"{found.relative_to(root_dir)}: Play listing assets must not be bundled in an app")


def check_png_rules(root_dir):
    for relative, (width, height, color_type, max_bytes) in BINARY_RULES.items():
        path = root_dir / relative
        if not path.is_file():
            raise IconError(f"{relative} is missing: run scripts/build-app-icon.py build")
        data = path.read_bytes()
        actual_width, actual_height, actual_type = png_header(data)
        if (actual_width, actual_height) != (width, height):
            raise IconError(f"{relative} is {actual_width}x{actual_height}, expected {width}x{height}")
        if actual_type != color_type:
            wanted = "RGB without an alpha channel" if color_type == 2 else "RGBA (32-bit)"
            raise IconError(f"{relative} must be {wanted} (colour type {color_type}), found {actual_type}"
                            + (": it has an alpha channel" if actual_type == 6 else ""))
        if len(data) > max_bytes:
            raise IconError(f"{relative} is {len(data)} bytes, over the {max_bytes} bytes limit")


def check_text_outputs(root_dir, outputs):
    for relative, expected in outputs.items():
        path = root_dir / relative
        if not path.is_file():
            raise IconError(f"{relative} is missing: run scripts/build-app-icon.py build")
        if path.read_text() != expected:
            raise IconError(f"{relative} does not match the source: run scripts/build-app-icon.py build "
                            "(generated files must not be edited by hand)")


def check_no_night_launcher(root_dir):
    for path in sorted((root_dir / ANDROID_RES).glob("*-night*/ic_launcher*")):
        raise IconError(f"{path.relative_to(root_dir)}: the icon is the same in light and dark (A6), "
                        "so there must be no -night launcher resource")


def encode_png(width, height, channels, pixels):
    """Deterministic PNG: 8-bit RGB or RGBA, 'Up' filter on every row, zlib level 9."""
    stride = width * channels
    rows, previous = [], bytes(stride)
    for y in range(height):
        row = pixels[y * stride:(y + 1) * stride]
        rows.append(b"\x02" + bytes((a - b) & 255 for a, b in zip(row, previous)))
        previous = row

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    header = struct.pack(">IIBBBBB", width, height, 8, 2 if channels == 3 else 6, 0, 0, 0)
    return (PNG_SIGNATURE + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(b"".join(rows), 9))
            + chunk(b"IEND", b""))


def png_chunks(data):
    if data[:8] != PNG_SIGNATURE:
        raise IconError("not a PNG file")
    position = 8
    while position + 8 <= len(data):
        length, kind = struct.unpack(">I4s", data[position:position + 8])
        body = data[position + 8:position + 8 + length]
        if len(body) != length:
            raise IconError("truncated PNG file")
        yield kind, body
        position += 12 + length


def png_header(data):
    """(width, height, colour type) of a PNG file."""
    kind, body = next(png_chunks(data), (None, b""))
    if kind != b"IHDR" or len(body) != 13:
        raise IconError("not a PNG file (no IHDR chunk)")
    width, height, _, color_type = struct.unpack(">IIBB", body[:10])
    return width, height, color_type


def decode_png(data):
    """(width, height, channels, pixels) for 8-bit non-interlaced RGB / RGBA PNGs; raises IconError otherwise."""
    width, height, color_type = png_header(data)
    chunks = list(png_chunks(data))
    depth, _, _, interlace = chunks[0][1][8], chunks[0][1][10], chunks[0][1][11], chunks[0][1][12]
    if depth != 8 or color_type not in (2, 6) or interlace != 0:
        raise IconError("only 8-bit non-interlaced RGB and RGBA PNG files are supported")
    channels = 3 if color_type == 2 else 4
    raw = zlib.decompress(b"".join(body for kind, body in chunks if kind == b"IDAT"))
    stride = width * channels
    if len(raw) != height * (stride + 1):
        raise IconError("PNG data has the wrong length")
    rows, previous = [], bytes(stride)
    for y in range(height):
        filter_type, line = raw[y * (stride + 1)], raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)]
        previous = unfilter(filter_type, bytearray(line), previous, channels)
        rows.append(bytes(previous))
    return width, height, channels, b"".join(rows)


def unfilter(filter_type, row, previous, bpp):
    if filter_type == 0:
        return row
    if filter_type == 2:
        return bytearray((a + b) & 255 for a, b in zip(row, previous))
    for i in range(len(row)):
        left = row[i - bpp] if i >= bpp else 0
        up = previous[i]
        up_left = previous[i - bpp] if i >= bpp else 0
        if filter_type == 1:
            prediction = left
        elif filter_type == 3:
            prediction = (left + up) // 2
        elif filter_type == 4:
            estimate = left + up - up_left
            distances = (abs(estimate - left), abs(estimate - up), abs(estimate - up_left))
            prediction = (left, up, up_left)[distances.index(min(distances))]
        else:
            raise IconError(f"unknown PNG filter type {filter_type}")
        row[i] = (row[i] + prediction) & 255
    return row


def to_rgb(png):
    """The same image without its alpha channel; fails if any pixel is not fully opaque (iOS icons: no alpha)."""
    width, height, channels, pixels = decode_png(png)
    if channels == 3:
        return png
    if pixels[3::4].count(255) != width * height:
        raise IconError("the image has transparent pixels, so its alpha channel cannot be dropped")
    rgb = bytearray(width * height * 3)
    for channel in range(3):
        rgb[channel::3] = pixels[channel::4]
    return encode_png(width, height, 3, bytes(rgb))


def to_rgba(png):
    width, height, channels, pixels = decode_png(png)
    if channels == 4:
        return png
    rgba = bytearray(b"\xff" * (width * height * 4))
    for channel in range(3):
        rgba[channel::4] = pixels[channel::3]
    return encode_png(width, height, 4, bytes(rgba))


def find_chrome():
    path = os.environ.get("CHROME") or DEFAULT_CHROME
    if not os.access(path, os.X_OK):
        raise IconError(f"Google Chrome not found at {path}: install it or set CHROME to its executable "
                        "(only `build` renders PNGs; `check` does not need Chrome)")
    return path


def svg_document(width, height, view_box, body, defs=""):
    return (f'<svg xmlns="{SVG_NS}" width="{width}" height="{height}" viewBox="{view_box}">'
            f"<defs>{defs}</defs>{body}</svg>")


def chrome_renderer(chrome):
    """render(svg_text, width, height) -> PNG bytes, through headless Chrome at 1 device pixel per unit."""
    def render(svg, width, height):
        with tempfile.TemporaryDirectory() as tmp:
            source, target = Path(tmp) / "input.svg", Path(tmp) / "output.png"
            source.write_text(svg)
            command = [chrome, "--headless", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                       f"--user-data-dir={Path(tmp) / 'profile'}", "--default-background-color=00000000",
                       f"--window-size={width},{height}", f"--screenshot={target}", source.as_uri()]
            subprocess.run(command, check=False, capture_output=True, timeout=120)
            if not target.is_file():
                raise IconError("Chrome did not produce a screenshot")
            return target.read_bytes()
    return render


def recolored(element, recolor):
    """The element as SVG text with every hex paint passed through `recolor`."""
    clone = copy.deepcopy(element)
    for node in clone.iter():
        for name in ("fill", "stroke", "stop-color"):
            if node.get(name) and HEX_PAINT.match(node.get(name)):
                node.set(name, recolor(node.get(name).upper()))
    return ET.tostring(clone, encoding="unicode")


def check_safe_zone_pixels(png, radius):
    """Fail if anything but faint anti-aliasing lies outside the circle (A3)."""
    width, height, channels, pixels = decode_png(png)
    for y in range(height):
        for x in range(width):
            offset = (y * width + x) * channels
            if max(pixels[offset:offset + 3]) > 32 and math.hypot(x + 0.5 - width / 2, y + 0.5 - height / 2) > radius + 1:
                raise IconError(f"the foreground leaves the safe zone (pixel {x},{y} is outside the "
                                f"{SAFE_ZONE_RADIUS * 2}-unit circle)")


def check_safe_zone(root, render):
    size = 108 * SAFE_ZONE_SCALE
    body = '<rect width="108" height="108" fill="#000000"/>' + recolored(find_part(root, "foreground"),
                                                                        lambda color: "#FFFFFF")
    png = render(svg_document(size, size, "0 0 108 108", body), size, size)
    check_safe_zone_pixels(png, SAFE_ZONE_RADIUS * SAFE_ZONE_SCALE)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def script_digest():
    return sha256(Path(__file__).read_bytes())


def write_manifest(root_dir, files):
    """Record the hashes that `check` verifies without Chrome (design 1.4)."""
    manifest = {"source": sha256((root_dir / SOURCE_RELATIVE).read_bytes()), "script": script_digest(),
                "files": {str(path): sha256(data) for path, data in files.items()}}
    (root_dir / MANIFEST_JSON_RELATIVE).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")


def verify_manifest(root_dir, expected_paths):
    path = root_dir / MANIFEST_JSON_RELATIVE
    if not path.is_file():
        raise IconError(f"{MANIFEST_JSON_RELATIVE} is missing: run scripts/build-app-icon.py build")
    manifest = json.loads(path.read_text())
    if manifest.get("source") != sha256((root_dir / SOURCE_RELATIVE).read_bytes()):
        raise IconError("the source changed since the last build: run scripts/build-app-icon.py build")
    if manifest.get("script") != script_digest():
        raise IconError("the build script changed since the last build: run scripts/build-app-icon.py build")
    listed = manifest.get("files", {})
    for relative in expected_paths:
        if str(relative) not in listed:
            raise IconError(f"{relative} is not recorded in {MANIFEST_JSON_RELATIVE}: run scripts/build-app-icon.py build")
        if not (root_dir / relative).is_file():
            raise IconError(f"{relative} is missing: run scripts/build-app-icon.py build")
        if sha256((root_dir / relative).read_bytes()) != listed[str(relative)]:
            raise IconError(f"{relative} was edited by hand or is stale: run scripts/build-app-icon.py build")


def check_manifest(root_dir):
    """The app declares the generated icons, never a system one (A1, A2)."""
    text = (root_dir / MANIFEST_RELATIVE).read_text()
    for attribute, resource in (("icon", "@mipmap/ic_launcher"), ("roundIcon", "@mipmap/ic_launcher_round")):
        found = re.search(rf'android:{attribute}="([^"]*)"', text)
        if not found or found.group(1) != resource:
            raise IconError(f"{MANIFEST_RELATIVE}: android:{attribute} must be {resource!r}, "
                            f"found {found.group(1) if found else 'nothing'!r}")
    if "@android:drawable" in text:
        raise IconError(f"{MANIFEST_RELATIVE}: no @android:drawable icon is allowed")


def command_build(root_dir, render=None):
    root = load_source(root_dir / SOURCE_RELATIVE)
    validate(root)
    render = render or chrome_renderer(find_chrome())  # fail before writing anything when Chrome is missing
    check_safe_zone(root, render)
    print("ok   the foreground fits the 66-unit safe zone")
    for relative, text in text_outputs(root).items():
        (root_dir / relative).parent.mkdir(parents=True, exist_ok=True)
        (root_dir / relative).write_text(text)
    print("ok   wrote the Android launcher layers and the iOS Contents.json")
    binaries = {path: make(root, render) for path, make in BINARY_ASSETS.items()}
    for relative, data in binaries.items():
        (root_dir / relative).parent.mkdir(parents=True, exist_ok=True)
        (root_dir / relative).write_bytes(data)
    write_manifest(root_dir, binaries)
    print(f"ok   wrote {len(binaries)} raster assets and {MANIFEST_JSON_RELATIVE}")


def command_check(root_dir):
    root = load_source(root_dir / SOURCE_RELATIVE)
    validate(root)
    print("ok   source uses only the allowed SVG subset")
    check_text_outputs(root_dir, text_outputs(root))
    check_no_night_launcher(root_dir)
    print("ok   Android launcher layers and iOS Contents.json match the source")
    check_manifest(root_dir)
    print("ok   the manifest declares the generated icons")
    check_png_rules(root_dir)
    print("ok   raster assets have the required size, colour type and weight")
    check_placement(root_dir)
    check_size_budget(root_dir)
    print("ok   Play assets stay out of the apps and the icon weight is within budget")
    verify_manifest(root_dir, list(BINARY_ASSETS))
    print("ok   the source, the script and the raster assets match the build manifest")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["check", "build"])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = parser.parse_args(argv)
    try:
        {"check": command_check, "build": command_build}[args.command](args.root)
    except IconError as error:
        print(f"FAIL {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
