def feature_graphic_svg(root):
    """1024x500 banner: the M and capsule (no tile) then the vector wordmark, centred in the 900x400 safe area."""
    width, height, unit, mark_scale, gap = 1024, 500, 5.2, 2.0, 50
    mark_width = 45.2 * unit  # horizontal extent of the foreground in canvas units (legs and their round caps)
    wordmark_width = 284.5 * mark_scale
    left = (width - (mark_width + gap + wordmark_width)) / 2
    mark = (f'<g transform="translate({fmt(left + mark_width / 2)} {height / 2}) scale({unit}) translate(-54 -55.9)">'
            + recolored(find_part(root, "foreground"), VARIANTS["light"]) + "</g>")
    name = (f'<g transform="translate({fmt(left + mark_width + gap)} {fmt(height / 2 - 18 * mark_scale)}) '
            f'scale({mark_scale})">' + recolored(find_part(root, "wordmark"), VARIANTS["light"]) + "</g>")
    gradients = "".join(recolored(g, VARIANTS["light"]) for g in root.iter() if local(g.tag) == "linearGradient")
    background = f'<rect width="{width}" height="{height}" fill="url(#teal)"/>'
    return svg_document(width, height, f"0 0 {width} {height}", background + mark + name, gradients)


