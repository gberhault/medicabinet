import xml.etree.ElementTree as ET
import zlib
from pathlib import Path

SOURCE_RELATIVE = Path("design/app-icon/medicabinet-icon.svg")
SVG_NS = "http://www.w3.org/2000/svg"
REQUIRED_PARTS = {"background": "rect", "foreground": "g", "wordmark": "g"}

SHAPE_ATTRS = {"id", "fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin"}
ALLOWED = {  # tag -> attributes it may carry
    "svg": {"xmlns", "viewBox", "width", "height"},
    "defs": set(),
    "linearGradient": {"id", "x1", "y1", "x2", "y2"},
    "stop": {"offset", "stop-color"},
    "g": SHAPE_ATTRS | {"transform"},
    "rect": SHAPE_ATTRS | {"x", "y", "width", "height"},
    "path": SHAPE_ATTRS | {"d"},
}
NUMBER = r"-?\d+(?:\.\d+)?"
TRANSFORM_OP = re.compile(
    rf"(?:translate\({NUMBER} {NUMBER}\)|scale\({NUMBER}\)|rotate\({NUMBER} {NUMBER} {NUMBER}\))"
)
PATH_DATA = re.compile(r"^[MmLlHhVvAaZz0-9.,\- ]{1,400}$")
HEX_PAINT = re.compile(r"^#[0-9A-Fa-f]{6}$")
LINECAPS, LINEJOINS = {"butt", "round", "square"}, {"miter", "round", "bevel"}


MANIFEST_JSON_RELATIVE = Path("design/app-icon/manifest.json")
DEFAULT_CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
SAFE_ZONE_RADIUS = 33  # the 66-unit circle every adaptive-icon mask keeps
SAFE_ZONE_SCALE = 2  # pixels per unit when the safe zone is checked
IOS_APPICONSET = Path("ios/MediCabinet/Resources/Assets.xcassets/AppIcon.appiconset")
IOS_APPEARANCES = ("light", "dark", "tinted")
TINTED_FLOOR = 160  # tinted icon: colours darker than this luminance become the black background
PLAY_VIEW_BOX = "18 18 72 72"  # the central 72 units of the 108-unit canvas, full-bleed, like the Play listing
PLAY_DIR = Path("design/app-icon/play")
PLAY_ICON = PLAY_DIR / "icon-512.png"
PLAY_GRAPHIC = PLAY_DIR / "feature-graphic-1024x500.png"
APP_BUDGET_BYTES = 100 * 1024  # X1: what the icon adds to either app
ANDROID_RES = Path("android/app/src/main/res")
MANIFEST_RELATIVE = Path("android/app/src/main/AndroidManifest.xml")
GENERATED = "Generated by scripts/build-app-icon.py from design/app-icon/medicabinet-icon.svg. Do not edit."
STYLE_DEFAULTS = {"fill": "#000000", "stroke": "none", "stroke-width": "1",
                  "stroke-linecap": "butt", "stroke-linejoin": "miter"}
OPEN_TRANSFORM = re.compile(r"(translate|scale|rotate)\(([^)]*)\)")

def tinted(color):
    """Greyscale by luminance, with the dark background colours pushed to black (iOS tinted appearance)."""
    red, green, blue = (int(color[i:i + 2], 16) for i in (1, 3, 5))
    luma = round(0.2126 * red + 0.7152 * green + 0.0722 * blue)
    return "#000000" if luma < TINTED_FLOOR else f"#{luma:02X}{luma:02X}{luma:02X}"


# A variant recolours every paint of the source (stops and shapes alike), so one drawing gives every asset.
VARIANTS = {
    "light": lambda color: color,
    "monochrome": lambda color: "#000000",  # Android 13+ tints the alpha silhouette itself
    "ios-dark": lambda color: {"#0D9488": "#134E4A", "#115E59": "#042F2E", "#FFFFFF": "#99F6E4"}.get(color, color),
    "ios-tinted": tinted,
}


ET.register_namespace("", SVG_NS)

# Raster assets: relative path -> function(root, render) returning PNG bytes; BINARY_RULES: path -> (width, height,
# PNG colour type, maximum bytes), enforced by `check` (colour type 2 = RGB without alpha, 6 = RGBA).
BINARY_ASSETS = {}
BINARY_RULES = {}


class IconError(Exception):
    """The source or a generated asset breaks a rule; the message names the culprit."""


def local(tag):
    return tag.split("}", 1)[1] if tag.startswith("{") else tag


def load_source(path):
    try:
        return ET.parse(path).getroot()
    except (OSError, ET.ParseError) as error:
        raise IconError(f"cannot read the source {path}: {error}") from error


def validate_transform(value, where):
    rest = value.strip()
    while rest:
        match = TRANSFORM_OP.match(rest)
        if not match:
            raise IconError(f"{where}: unsupported transform {value!r} (use translate(x y), scale(s), rotate(a cx cy))")
        rest = rest[match.end():].lstrip()


def validate(root):
    """Reject anything outside the allowed subset (R1); the message names the element and attribute."""
    if local(root.tag) != "svg" or root.get("viewBox") is None:
        raise IconError("the source root must be an <svg> with a viewBox")
    gradients = {e.get("id") for e in root.iter() if local(e.tag) == "linearGradient"}
    for element in root.iter():
        tag = local(element.tag)
        if tag not in ALLOWED:
            raise IconError(f"<{tag}> is not allowed in the icon source (allowed: {', '.join(sorted(ALLOWED))})")
        if element.text and element.text.strip():
            raise IconError(f"<{tag}> must not contain text")
        where = f"<{tag}{' id=' + element.get('id') if element.get('id') else ''}>"
        for name, value in element.attrib.items():
            if name.startswith("{") or name not in ALLOWED[tag]:
                raise IconError(f"{where}: attribute {name!r} is not allowed")
            if name in ("fill", "stroke", "stop-color"):
                validate_paint(value, gradients, where, name)
            elif name == "transform":
                validate_transform(value, where)
            elif name == "d" and not PATH_DATA.match(value):
                raise IconError(f"{where}: unsupported path data {value[:40]!r}")
            elif name == "stroke-linecap" and value not in LINECAPS:
                raise IconError(f"{where}: bad stroke-linecap {value!r}")
            elif name == "stroke-linejoin" and value not in LINEJOINS:
                raise IconError(f"{where}: bad stroke-linejoin {value!r}")
    for part, tag in REQUIRED_PARTS.items():
        found = [e for e in root.iter() if e.get("id") == part and local(e.tag) == tag]
        if len(found) != 1:
            raise IconError(f"the source must contain exactly one <{tag} id={part!r}>")


def validate_paint(value, gradients, where, name):
    if value == "none" or HEX_PAINT.match(value):
        return
    match = re.fullmatch(r"url\(#([A-Za-z0-9_-]+)\)", value)
    if match:
        if match.group(1) not in gradients:
            raise IconError(f"{where}: {name} refers to the unknown gradient {match.group(1)!r}")
        return
    raise IconError(f"{where}: unsupported paint {value!r} for {name} (use #RRGGBB, none or url(#gradient))")


def fmt(value):
    text = f"{float(value):.4f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


def find_part(root, part):
    return next(e for e in root.iter() if e.get("id") == part)


def read_gradients(root):
    gradients = {}
    for gradient in (e for e in root.iter() if local(e.tag) == "linearGradient"):
        box = tuple(float(gradient.get(k, d)) for k, d in (("x1", 0), ("y1", 0), ("x2", 1), ("y2", 0)))
        stops = [(float(stop.get("offset")), stop.get("stop-color")) for stop in gradient]
        gradients[gradient.get("id")] = (box, stops)
    return gradients


def walk(element, style, gradients, recolor):
    """Turn a source element into groups and paths (tuples), resolving inherited paint and transforms."""
    tag = local(element.tag)
    style = {**style, **{k: v for k, v in element.attrib.items() if k in STYLE_DEFAULTS}}
    if tag == "g":
        children = [node for child in element for node in walk(child, style, gradients, recolor)]
        for operation in reversed(OPEN_TRANSFORM.findall(element.get("transform", ""))):
            children = [("group", group_attributes(*operation), children)]
        return children
    if tag == "rect":
        x, y, w, h = (float(element.get(k)) for k in ("x", "y", "width", "height"))
        data = f"M{fmt(x)},{fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}z"
        fill = paint(style["fill"], gradients, recolor, (x, y, w, h))
    else:
        data = element.get("d")
        fill = paint(style["fill"], gradients, recolor, None)
    stroke = paint(style["stroke"], gradients, recolor, None)
    return [("path", data, fill, stroke, style["stroke-width"], style["stroke-linecap"], style["stroke-linejoin"])]


def group_attributes(operation, arguments):
    numbers = arguments.split()
    if operation == "translate":
        return [("translateX", numbers[0]), ("translateY", numbers[1])]
    if operation == "scale":
        return [("scaleX", numbers[0]), ("scaleY", numbers[0])]
    return [("rotation", numbers[0]), ("pivotX", numbers[1]), ("pivotY", numbers[2])]


def paint(value, gradients, recolor, box):
    """None, a '#RRGGBB' colour, or a ('gradient', start/end in canvas units, stops) tuple (rect only)."""
    if value == "none":
        return None
    if not value.startswith("url("):
        return recolor(value.upper())
    if box is None:
        raise IconError("a gradient fill is only supported on a <rect> (Android vector gradients need the shape's box)")
    (x1, y1, x2, y2), stops = gradients[value[5:-1]]
    x, y, w, h = box
    line = (x + x1 * w, y + y1 * h, x + x2 * w, y + y2 * h)
    stops = [(offset, recolor(color.upper())) for offset, color in stops]
    if len({color for _, color in stops}) == 1:  # a variant that flattens the colours needs no gradient
        return stops[0][1]
    return ("gradient", line, stops)


def argb(color):
    return "#FF" + color[1:]


def render_node(node, depth):
    pad = "    " * depth
    if node[0] == "group":
        attributes = "".join(f' android:{name}="{fmt(value)}"' for name, value in node[1])
        inner = "".join(render_node(child, depth + 1) for child in node[2])
        return f"{pad}<group{attributes}>\n{inner}{pad}</group>\n"
    _, data, fill, stroke, width, cap, join = node
    lines = [f'{pad}<path android:pathData="{data}"']
    if fill and fill[0] != "gradient":
        lines.append(f'{pad}    android:fillColor="{argb(fill)}"')
    if stroke:
        lines += [f'{pad}    android:strokeColor="{argb(stroke)}"', f'{pad}    android:strokeWidth="{fmt(width)}"',
                  f'{pad}    android:strokeLineCap="{cap}"', f'{pad}    android:strokeLineJoin="{join}"']
    head = "\n".join(lines)
    if not (fill and fill[0] == "gradient"):
        return head + "/>\n"
    _, (x1, y1, x2, y2), stops = fill
    items = "".join(f'{pad}            <item android:offset="{fmt(o)}" android:color="{argb(c)}"/>\n' for o, c in stops)
    return (f'{head}>\n{pad}    <aapt:attr name="android:fillColor">\n'
            f'{pad}        <gradient android:type="linear" android:startX="{fmt(x1)}" android:startY="{fmt(y1)}" '
            f'android:endX="{fmt(x2)}" android:endY="{fmt(y2)}">\n{items}{pad}        </gradient>\n'
            f'{pad}    </aapt:attr>\n{pad}</path>\n')


def vector_drawable(root, part, recolor):
    """The VectorDrawable for one part of the source (108x108 adaptive-icon layer)."""
    nodes = walk(find_part(root, part), dict(STYLE_DEFAULTS), read_gradients(root), recolor)
    body = "".join(render_node(node, 1) for node in nodes)
    aapt = ' xmlns:aapt="http://schemas.android.com/aapt"' if "<aapt:attr" in body else ""
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f"<!-- {GENERATED} -->\n"
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{aapt}\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            f"{body}</vector>\n")


def adaptive_icon_xml():
    layers = "".join(f'    <{layer} android:drawable="@drawable/ic_launcher_{layer}"/>\n'
                     for layer in ("background", "foreground", "monochrome"))
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f"<!-- {GENERATED} -->\n"
            f'<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n{layers}</adaptive-icon>\n')


def android_outputs(root):
    """Relative path -> text of every generated Android file (source `root` is the parsed SVG)."""
    drawable, mipmap = ANDROID_RES / "drawable", ANDROID_RES / "mipmap-anydpi"
    return {
        drawable / "ic_launcher_background.xml": vector_drawable(root, "background", VARIANTS["light"]),
        drawable / "ic_launcher_foreground.xml": vector_drawable(root, "foreground", VARIANTS["light"]),
        drawable / "ic_launcher_monochrome.xml": vector_drawable(root, "foreground", VARIANTS["monochrome"]),
        mipmap / "ic_launcher.xml": adaptive_icon_xml(),
        mipmap / "ic_launcher_round.xml": adaptive_icon_xml(),
    }


def icon_svg(root, recolor, size, view_box=PLAY_VIEW_BOX):
    """The full-bleed square icon (background + foreground) in one variant, ready for Chrome."""
    gradients = "".join(recolored(g, recolor) for g in root.iter() if local(g.tag) == "linearGradient")
    body = recolored(find_part(root, "background"), recolor) + recolored(find_part(root, "foreground"), recolor)
    return svg_document(size, size, view_box, body, gradients)


def ios_outputs(root):
    """Contents.json: the light icon plus the dark and tinted appearances of iOS 18 (iOS 17 shows the light one)."""
    images = []
    for appearance in IOS_APPEARANCES:
        image = {"filename": f"AppIcon-{appearance}.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"}
        if appearance != "light":
            image["appearances"] = [{"appearance": "luminosity", "value": appearance}]
        images.append(image)
    contents = {"images": images, "info": {"author": "xcode", "version": 1}}
    return {IOS_APPICONSET / "Contents.json": json.dumps(contents, indent=2, sort_keys=True) + "\n"}


def text_outputs(root):
    return {**android_outputs(root), **ios_outputs(root)}


